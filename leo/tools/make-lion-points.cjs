// Usage: npm i pngjs && node tools/make-lion-points.cjs 16000
// Sample the Leo Tech emblem into particle positions + per-theme colours for the three.js hero.
const fs = require('fs');
const { PNG } = require('pngjs');
const path = require('path');
const LOGO = path.join(__dirname, '../logo/png');
const dark = PNG.sync.read(fs.readFileSync(`${LOGO}/leo-tech-icon-dark.png`));
const light = PNG.sync.read(fs.readFileSync(`${LOGO}/leo-tech-icon-light.png`));
const W = dark.width, H = dark.height, N = Number(process.argv[2] || 15000);

// deterministic RNG so rebuilds give the same lion
let seed = 20261001; const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);

const pos = new Int16Array(N * 3), cDark = new Uint8Array(N * 3), cLight = new Uint8Array(N * 3);
let n = 0, tries = 0, inked = 0;
for (let i = 3; i < dark.data.length; i += 4) if (dark.data[i] >= 150) inked++;
const step = Math.sqrt(inked / N) * 0.985;
for (let gy = step / 2; gy < H && n < N; gy += step) for (let gx = step / 2; gx < W && n < N; gx += step) {
  tries++;
  const px = Math.min(W - 1, Math.max(0, gx + (rnd() - 0.5) * step * 0.7)), py = Math.min(H - 1, Math.max(0, gy + (rnd() - 0.5) * step * 0.7));
  const x0 = Math.floor(px), y0 = Math.floor(py), k = (y0 * W + x0) * 4;
  if (dark.data[k + 3] < 150) continue;
  const x = (px / W) * 2 - 1, y = -((py / H) * 2 - 1);
  const isBlue = light.data[k + 2] > 150 && light.data[k] < 120;
  const dome = 0.26 * Math.sqrt(Math.max(0, 1 - (x * x + y * y) / 0.95));
  const z = dome + (isBlue ? 0.05 : -0.03) + (rnd() - 0.5) * 0.05;
  pos[n * 3] = Math.round(x * 32000); pos[n * 3 + 1] = Math.round(y * 32000); pos[n * 3 + 2] = Math.round(z * 32000);
  for (let c = 0; c < 3; c++) { cDark[n * 3 + c] = dark.data[k + c]; cLight[n * 3 + c] = light.data[k + c]; }
  n++;
}
// shuffle so mobile's every-other-point subsample stays even
for (let i = n - 1; i > 0; i--) {
  const j = Math.floor(rnd() * (i + 1));
  for (let c = 0; c < 3; c++) {
    let t = pos[i * 3 + c]; pos[i * 3 + c] = pos[j * 3 + c]; pos[j * 3 + c] = t;
    t = cDark[i * 3 + c]; cDark[i * 3 + c] = cDark[j * 3 + c]; cDark[j * 3 + c] = t;
    t = cLight[i * 3 + c]; cLight[i * 3 + c] = cLight[j * 3 + c]; cLight[j * 3 + c] = t;
  }
}
const b64 = (a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString('base64');
const js = `/* Leo Tech emblem as particles: generated by tools/make-lion-points.cjs from logo/png/leo-tech-icon-{dark,light}.png. Do not edit by hand. */
window.LEO_LION={count:${n},unit:${1 / 32000},pos:"${b64(pos.subarray(0, n * 3))}",dark:"${b64(cDark.subarray(0, n * 3))}",light:"${b64(cLight.subarray(0, n * 3))}"};
`;
fs.writeFileSync(path.join(__dirname, '../website/assets/js/lion-points.js'), js);
console.log('points', n, 'tries', tries, 'bytes', js.length);
